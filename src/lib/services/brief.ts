/**
 * Pre-visit brief: what was agreed last time, which APPROVED practice is most relevant to this visit's purpose and what to
 * look for. Built only from the mentor's own saved records and approved practice cards. No teacher-level judgement,
 * no public statistics, nothing generated by a model.
 */
export interface PreVisitBrief {
  visit: { id: string; school_name: string; scheduled_at: string; grade: number; subject: string; teacher_alias: string; purpose: string; coaching_focus: string | null; prep_notes: string | null };
  previous: null | { id: string; action_text: string; expected_evidence: string; target_date: string; display_status: string; origin_visit_date: string };
  card: null | {
    id: string; title: string; domain: string; origin: "illustrative" | "official_source"; source_title: string; source_url: string | null;
    reasons: string[]; look_for: string[]; try_prompts: string[]; language_of_text: Lang;
  };
  /** True when no approved card matched; the mentor then plans manually. */
  insufficient_evidence: boolean;
}

export function getPreVisitBrief(db: Db, actor: Actor, visitId: string): PreVisitBrief {
  const visit = getAuthorizedVisit(db, actor, visitId, "content");
  const school = get<{ name: string }>(db, "SELECT name FROM schools WHERE id = ?", visit.school_id);

  const prevSql = `SELECT * FROM commitments WHERE status IN ('open','completed') AND visit_id <> ?
       AND visit_id IN (SELECT id FROM visits WHERE school_id = ? AND mentor_id = ? AND teacher_alias = ?)`;
  const prevRow = visit.previous_commitment_id
    ? get<CommitmentRow>(db, "SELECT * FROM commitments WHERE id = ?", visit.previous_commitment_id)
    : get<CommitmentRow>(db, `${prevSql} ORDER BY target_date LIMIT 1`, visit.id, visit.school_id, visit.mentor_id, visit.teacher_alias);
  const prevVisit = prevRow ? get<{ scheduled_at: string; mentor_id: string }>(db, "SELECT scheduled_at, mentor_id FROM visits WHERE id = ?", prevRow.visit_id) : undefined;
  const previous = prevRow && prevVisit?.mentor_id === actor.id
    ? {
        id: prevRow.id, action_text: prevRow.action_text, expected_evidence: prevRow.expected_evidence, target_date: prevRow.target_date,
        display_status: displayStatus(prevRow.status, prevRow.target_date), origin_visit_date: prevVisit.scheduled_at,
      }
    : null;

  const { candidates } = keywordRetriever(getApprovedCards(db), {
    grade: visit.grade,
    subject: visit.subject,
    language: visit.language,
    fields: [
      { text: visit.purpose, weight: 2 },
      { text: visit.coaching_focus ?? "", weight: 3 },
      { text: visit.prep_notes ?? "", weight: 1 },
      { text: previous?.action_text ?? "", weight: 2 },
    ],
    confirmedTagCodes: [],
    confirmedTagDomains: [],
  });
  const best = candidates[0];
  const card = best ? getApprovedCards(db).find((c) => c.id === best.card_id) : undefined;
  const hi = visit.language === "hi" ? card?.localized.hi : undefined;
  return {
    visit: {
      id: visit.id, school_name: school?.name ?? "", scheduled_at: visit.scheduled_at, grade: visit.grade, subject: visit.subject,
      teacher_alias: visit.teacher_alias, purpose: visit.purpose, coaching_focus: visit.coaching_focus, prep_notes: visit.prep_notes,
    },
    previous,
    card: card && best
      ? {
          id: card.id, title: hi?.title ?? card.title, domain: card.domain, origin: card.origin, source_title: card.source_title,
          source_url: card.source_url, reasons: best.reasons.slice(0, 2),
          look_for: (hi?.steps ?? card.steps).slice(0, 3),
          try_prompts: (hi?.prompts ?? card.example_prompts).slice(0, 2),
          language_of_text: hi ? "hi" : "en",
        }
      : null,
    insufficient_evidence: !card,
  };
}

/**
 * Teacher-facing action summary: the ONE agreed next step, how to try it, and what the mentor will look for next time.
 * It restates what the mentor approved (feedback) and agreed (commitment); it adds no new judgement and no score.
 * Available only after the feedback is approved and a next step has been agreed.
 */
export interface ActionSummary {
  visit_id: string;
  school_name: string;
  visit_date: string;
  teacher_alias: string;
  language: Lang;
  strength: string | null;
  next_step: string;
  how_to_try: string[];
  review_on: string;
  look_for_next_time: string;
  source: { card_title: string; source_title: string } | null;
  approved_by_mentor: { name: string; at: string };
  simulated_draft: boolean;
}

export function getActionSummary(db: Db, actor: Actor, visitId: string): ActionSummary {
  const visit = getAuthorizedVisit(db, actor, visitId, "content");
  const fb = currentFeedbackInternal(db, visitId);
  if (!fb || fb.status !== "approved" || !fb.next_step || !fb.approved_at) {
    throw conflict("feedback_not_approved", "Approve the feedback card first. The teacher summary is built from its approved next step.");
  }
  const commitment = get<CommitmentRow>(db, "SELECT * FROM commitments WHERE visit_id = ? AND status <> 'cancelled' ORDER BY created_at DESC LIMIT 1", visitId);
  if (!commitment) throw conflict("commitment_missing", "Agree the next step with the teacher first. The summary shows what you agreed.");
  const school = get<{ name: string }>(db, "SELECT name FROM schools WHERE id = ?", visit.school_id);
  const demo = currentDemoInternal(db, visitId);
  const approver = get<{ display_name: string }>(db, "SELECT display_name FROM profiles WHERE id = ?", fb.approved_by);
  const primary = fb.citations.find((c) => c.is_primary) ?? fb.citations[0];
  return {
    visit_id: visitId,
    school_name: school?.name ?? "",
    visit_date: visit.scheduled_at,
    teacher_alias: visit.teacher_alias,
    language: fb.language,
    strength: fb.strength,
    next_step: commitment.action_text,
    how_to_try: demo && demo.status === "approved" ? demo.steps.slice(0, 4).map((s) => s.action) : [],
    review_on: commitment.target_date,
    look_for_next_time: commitment.expected_evidence,
    source: primary ? { card_title: getCardInternal(db, primary.practice_card_id)?.title ?? primary.source_title, source_title: primary.source_title } : null,
    approved_by_mentor: { name: approver?.display_name ?? "", at: fb.approved_at },
    simulated_draft: fb.is_simulated,
  };
}
